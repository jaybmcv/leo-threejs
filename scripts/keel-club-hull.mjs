// Writes src/walk/keel-club-hull.js: the v2 hull's inner half-width (skin minus the 2.5 m inset every room keeps)
// on a grid under Deck 1, so the Keel Club can follow the hull without building the hull loft at walk time; and the
// hull's bottom (the outer skin's height) on a grid across the floor, so the club's water basins stay inside the skin.
// Run: node scripts/keel-club-hull.mjs
import fs from 'node:fs';
import {hullV2} from '../src/plan/hull-v2.js';
const h=hullV2(),X0=-160,X1=216,DX=2,Y0=-52,Y1=-39.5,DY=.5;
const xs=Math.round((X1-X0)/DX)+1,ys=Math.round((Y1-Y0)/DY)+1,rows=[];
for(let j=0;j<ys;j++){const y=Y0+j*DY,row=[];for(let i=0;i<xs;i++)row.push(+Math.max(0,h.skin(X0+i*DX,y)-2.5).toFixed(2));rows.push(row);}
// The bottom: at (x, z), the lowest y where the skin's half-width reaches |z| (bisected; the hull widens upwards here),
// rounded up to the centimetre, so a basin kept above it is never below the skin by the rounding.
const Z1=50,DZ=2,zs=Math.round(Z1/DZ)+1,bottom=[];
for(let i=0;i<xs;i++){const x=X0+i*DX,row=[];for(let k=0;k<zs;k++){const z=Math.max(.01,k*DZ);let lo=-60,hi=-44;
  for(let n=0;n<40;n++){const m=(lo+hi)/2;if(h.skin(x,m)>=z)hi=m;else lo=m;}row.push(+(Math.ceil(hi*100)/100).toFixed(2));}bottom.push(row);}
const out=`// Generated by scripts/keel-club-hull.mjs from src/plan/hull-v2.js. Do not edit.
// Inner half-width of the hull (skin minus 2.5 m) under Deck 1: HALF[j][i] at x=${X0}+${DX}i, y=${Y0}+${DY}j.
export const KEEL_HULL={x0:${X0},dx:${DX},nx:${xs},y0:${Y0},dy:${DY},ny:${ys}};
export const HALF=${JSON.stringify(rows)};
// The hull's bottom (its outer skin's height) under the club's floor: BOTTOM[i][k] at x=${X0}+${DX}i, |z|=${DZ}k.
export const KEEL_BOTTOM={x0:${X0},dx:${DX},nx:${xs},dz:${DZ},nz:${zs}};
export const BOTTOM=${JSON.stringify(bottom)};
`;
fs.writeFileSync(new URL('../src/walk/keel-club-hull.js',import.meta.url),out);
console.log('wrote',xs,'x',ys,'half-widths and',xs,'x',zs,'bottom heights,',out.length,'bytes');
