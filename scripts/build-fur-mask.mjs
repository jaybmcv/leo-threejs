import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createCanvas,loadImage} from '@napi-rs/canvas';

// The authored blue islands of Cosmo's body atlas, including their dark edges.
// Eyes, lashes, mouth, inner ears and nose have no blue coverage. Clothing uses another atlas.
const source=await fs.readFile('src/vendor/cosmo/DLCat.js','utf8'),images=JSON.parse(source.match(/var images = (.*);/)[1]);
const bytes=Buffer.from(images[1].dataUri.split(',')[1],'base64'),image=await loadImage(bytes);
const canvas=createCanvas(image.width,image.height),ctx=canvas.getContext('2d');ctx.drawImage(image,0,0);
const pixels=ctx.getImageData(0,0,image.width,image.height),mask=ctx.createImageData(image.width,image.height);
let fur=0;
for(let i=0;i<pixels.data.length;i+=4){const [r,g,b]=pixels.data.subarray(i,i+3),v=b>40&&b>r*1.5&&b>g*1.5?255:0;
 mask.data.set([v,v,v,255],i);if(v)fur++;}
ctx.putImageData(mask,0,0);const png=canvas.toBuffer('image/png');
const runs=[];let value=0,length=0;
for(let i=0;i<mask.data.length;i+=4){const next=mask.data[i];if(next!==value){runs.push(length);length=0;value=next;}length++;}runs.push(length);
await fs.writeFile('src/walk/fur-mask.js',`// Generated by scripts/build-fur-mask.mjs. White is fur; black preserves the atlas.\nexport const FUR_ATLAS_SHA='${createHash('sha256').update(bytes).digest('hex')}';\nexport const FUR_MASK_SIZE=[${image.width},${image.height}];\n// Alternating black and white run lengths, starting with black.\nexport const FUR_MASK_RUNS=${JSON.stringify(runs)};\nexport const FUR_MASK='data:image/png;base64,${png.toString('base64')}';\n`);
await fs.mkdir('output/fur-review',{recursive:true});await fs.writeFile('output/fur-review/mask.png',png);
console.log(`Fur mask: ${fur} of ${image.width*image.height} texels, ${png.length} bytes`);
