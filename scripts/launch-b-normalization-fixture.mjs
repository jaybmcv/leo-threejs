import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {Document,NodeIO} from '@gltf-transform/core';
import {normalizeExteriorBeforeRooms} from './normalize-exterior-before-rooms-v2.mjs';
assert.equal(process.env.LEO_LAYOUT,'2');
await fs.mkdir('output/launch-b',{recursive:true});
const out=await fs.mkdtemp(path.resolve('output/launch-b/normalization-fixture-'));
const io=new NodeIO(),doc=new Document();doc.createScene();const bytes=await io.writeBinary(doc);
for(const name of ['leo-exterior','leo-exterior-refined','leo-exterior-web','leo-exterior-phone'])await fs.writeFile(out+'/'+name+'.glb',bytes);
await fs.writeFile(out+'/exterior-envelopes.json','{}');
await assert.rejects(fs.access(out+'/walk-plan.json'));
const pkg=JSON.parse(await fs.readFile('package.json','utf8')),entry=await fs.readFile('scripts/build-all.mjs','utf8');
assert.equal(pkg.scripts.build,'node scripts/build-all.mjs');
assert(entry.includes("await import('./build-v2.mjs')"),'Normal npm entry must run the tested v2 producer');
const build=await fs.readFile('scripts/build-v2.mjs','utf8');
assert(build.indexOf('normalizeExteriorBeforeRooms()')<build.indexOf("await runV2('build')"));
await normalizeExteriorBeforeRooms({out,evidence:out+'/evidence'});
await assert.rejects(fs.access(out+'/walk-plan.json'));
const full=spawnSync(process.execPath,['scripts/retire-obsolete-facades-v2.mjs'],{encoding:'utf8',windowsHide:true,env:{...process.env,LEO_SCOPED_OUTPUT:out,LEO_SCOPED_EVIDENCE:out+'/evidence'}});
assert.notEqual(full.status,0,'Full finalization must still require its walk plan');
assert.match(full.stderr,/walk-plan[.]json/);
await fs.writeFile('output/launch-b/normalization-fixture.json',JSON.stringify({status:'PASS',normalEntryOrder:true,exteriorOnlyWithNoWalkPlan:true,fullFinalizationRequiresPlan:true},null,2));
console.log('PASS normal early exterior normalization without walk-plan; full finalization still requires it');
